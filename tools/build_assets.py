"""Build the intro assets for the wedding site from the extracted video frames.

usage: python3 -I build_assets.py <frames_dir> <project_dir> <ffmpeg>
"""
import json, os, shutil, subprocess, sys
import cv2, numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # detext.py lives next to this file
from detext import detext, text_mask  # noqa: E402

FR, PROJ, FF = sys.argv[1], sys.argv[2], sys.argv[3]
FPS = 30000 / 1001
SCRUB_END = 165            # last frame before the baked-in title starts to appear
LOOP_A, LOOP_B, XF = 216, 480, 30   # ambient loop source range + seam crossfade length

load = lambda i: cv2.imread(os.path.join(FR, f"f{i:03d}.png"))
intro_dir = os.path.join(PROJ, "assets", "intro"); os.makedirs(intro_dir, exist_ok=True)
for f in os.listdir(intro_dir): os.remove(os.path.join(intro_dir, f))

# ---- 1. adaptive sampling of the scroll-scrubbed part (keep frames where motion accumulates)
small = lambda im: cv2.resize(im, (176, 325)).astype(np.float32)
prev = small(load(0)); acc = 0.0; motion = [0.0]
for i in range(1, SCRUB_END + 1):
    cur = small(load(i)); motion.append(float(np.abs(cur - prev).mean())); prev = cur
budget = 118
total = sum(motion); step = total / budget
keep = [0]; acc = 0.0
for i in range(1, SCRUB_END + 1):
    acc += motion[i]
    if acc >= step or i - keep[-1] >= 4:   # never leave more than 4 frames between samples
        keep.append(i); acc = 0.0
if keep[-1] != SCRUB_END: keep.append(SCRUB_END)

manifest = []
for n, i in enumerate(keep):
    name = f"{n:03d}.webp"
    cv2.imwrite(os.path.join(intro_dir, name), load(i), [cv2.IMWRITE_WEBP_QUALITY, 62])
    manifest.append([name, i])

# ---- 2. seamless, text-free ambient loop  (out[0] == src[LOOP_B+1] so the loop wraps cleanly)
tmp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "loopframes")
shutil.rmtree(tmp, ignore_errors=True); os.makedirs(tmp)
n_out = LOOP_B - LOOP_A + 1
for j in range(n_out):
    a = detext(load(LOOP_A + j))
    if j < XF:
        w = j / XF
        b = detext(load(LOOP_B + 1 + j))
        a = cv2.addWeighted(b, 1 - w, a, w, 0)
    cv2.imwrite(os.path.join(tmp, f"{j:04d}.png"), a)
    if j == 0:
        first = a
cv2.imwrite(os.path.join(intro_dir, "end.webp"), first, [cv2.IMWRITE_WEBP_QUALITY, 70])
cv2.imwrite(os.path.join(PROJ, "assets", "scene-poster.jpg"), first, [cv2.IMWRITE_JPEG_QUALITY, 80])
subprocess.run([FF, "-y", "-loglevel", "error", "-framerate", "30000/1001", "-i", os.path.join(tmp, "%04d.png"),
                "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "24", "-preset", "slow",
                "-movflags", "+faststart", "-an", os.path.join(PROJ, "assets", "scene-loop.mp4")], check=True)

# ---- 3. title layout measured from a settled frame (fractions of the 702x1300 frame)
f = load(400); H, W = f.shape[:2]
m = text_mask(f) > 0
rows = np.where(m.any(axis=1))[0]
lines, start = [], rows[0]
for a, b in zip(rows, rows[1:]):
    if b - a > 6: lines.append((start, a)); start = b
lines.append((start, rows[-1]))
layout = []
for y0, y1 in lines:
    xs = np.where(m[y0:y1 + 1].any(axis=0))[0]
    layout.append(dict(y0=round(y0 / H, 4), y1=round(y1 / H, 4), x0=round(xs.min() / W, 4), x1=round(xs.max() / W, 4)))
px = f[cv2.erode(m.astype(np.uint8), np.ones((3, 3), np.uint8)) > 0].astype(np.float32)
L = px.mean(axis=1); col = px[L < np.percentile(L, 40)].mean(axis=0)

with open(os.path.join(PROJ, "js", "intro-manifest.js"), "w") as fh:
    fh.write("// Generated by the asset pipeline: [file, source video frame] at %.3f fps.\n" % FPS)
    fh.write("window.INTRO_FRAMES = " + json.dumps(manifest) + ";\n")
    fh.write("window.INTRO_FPS = %.5f;\n" % FPS)

print("scrub frames", len(manifest), "of", SCRUB_END + 1)
print("intro MB", round(sum(os.path.getsize(os.path.join(intro_dir, x)) for x in os.listdir(intro_dir)) / 1e6, 2))
print("loop MB", round(os.path.getsize(os.path.join(PROJ, "assets", "scene-loop.mp4")) / 1e6, 2), "frames", n_out)
print("title lines", json.dumps(layout))
print("text colour RGB", col[::-1].round())
